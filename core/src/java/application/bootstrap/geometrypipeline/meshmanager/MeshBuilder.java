package application.bootstrap.geometrypipeline.meshmanager;

import java.io.File;

import application.bootstrap.geometrypipeline.ibo.IBOHandle;
import application.bootstrap.geometrypipeline.ibomanager.IBOManager;
import application.bootstrap.geometrypipeline.mesh.MeshHandle;
import application.bootstrap.geometrypipeline.mesh.RiggedMeshStruct;
import application.bootstrap.geometrypipeline.rig.RigHandle;
import application.bootstrap.geometrypipeline.rigmanager.RigManager;
import application.bootstrap.geometrypipeline.subvoxelmanager.SubVoxelManager;
import application.bootstrap.geometrypipeline.subvoxelmanager.SubVoxelMeshUtility;
import application.bootstrap.geometrypipeline.vao.VAOInstance;
import application.bootstrap.geometrypipeline.vbo.VBOHandle;
import application.bootstrap.geometrypipeline.vbomanager.VBOManager;
import engine.root.BuilderPackage;
import engine.root.EngineSetting;
import engine.util.arpg.ArpgArrayStruct;
import engine.util.arpg.ArpgElementStruct;
import engine.util.arpg.ArpgObjectStruct;
import engine.util.arpg.ArpgUtility;
import engine.util.io.FileUtility;
import engine.util.mathematics.vectors.Vector3;
import it.unimi.dsi.fastutil.floats.FloatArrayList;
import it.unimi.dsi.fastutil.shorts.ShortArrayList;

class MeshBuilder extends BuilderPackage {

    /*
     * Assembles a MeshHandle from registered VAO, VBO and IBO data, expanding
     * quad entries inline; a plain quad carries its own vertex data whole.
     * Rigged meshes are parsed into a RiggedMeshStruct and built through
     * MeshManager — per-corner bone weights, smooth normals, zones, masks and
     * the morph texture their handle receives — the same
     * path the character editor rebuilds them with; they record their raw
     * bounds. Meshes declaring subvoxels are generated by SubVoxelManager
     * instead. A rigged or sub-voxel mesh records the tiles its vertices draw
     * from, for texture streaming. Bootstrap only.
     */

    // Internal
    private MeshManager meshManager;
    private VBOManager vboManager;
    private IBOManager iboManager;
    private RigManager rigManager;
    private SubVoxelManager subVoxelManager;

    // Base \\

    @Override
    protected void get() {
        this.meshManager = get(MeshManager.class);
        this.vboManager = get(VBOManager.class);
        this.iboManager = get(IBOManager.class);
        this.rigManager = get(RigManager.class);
        this.subVoxelManager = get(SubVoxelManager.class);
    }

    // Build \\

    MeshHandle buildMeshHandle(
            File root,
            File file,
            VAOInstance vaoInstance) {

        ArpgObjectStruct arpg = ArpgUtility.loadObject(file);
        String resourceName = FileUtility.getPathWithFileNameWithoutExtension(root, file);
        RigHandle rigHandle = resolveRig(arpg);
        boolean hasQuads = hasQuadEntries(arpg);
        boolean hasSubVoxels = subVoxelManager.hasSubVoxels(arpg);

        if (hasSubVoxels && (rigHandle != null || hasQuads))
            throwException("Sub-voxel mesh \"" + resourceName + "\" cannot also declare a rig or quad entries — "
                    + "its geometry is generated entirely from its cubes. File: " + file.getName());

        if (rigHandle != null && !hasQuads)
            throwException("Rigged mesh \"" + resourceName + "\" must declare its vertex data through quad "
                    + "entries — bone weighting and entity-scale bounds can only be resolved from quad-expanded "
                    + "vertex data. File: " + file.getName());

        VBOHandle vboHandle;
        IBOHandle iboHandle;
        Vector3 boundsMin;
        Vector3 boundsMax;
        QuadExpansionStruct riggedExpansion = null;
        float[] subVoxelVertices = null;

        if (hasQuads) {

            QuadExpansionStruct expansion = rigHandle != null
                    ? expandRigged(arpg, vaoInstance, file)
                    : expandVBO(arpg, vaoInstance, file);
            riggedExpansion = rigHandle != null ? expansion : null;
            vboHandle = vboManager.addVBOFromData(resourceName, expansion.vertices, vaoInstance);
            iboHandle = iboManager.addIBOFromData(resourceName, expansion.indices, vaoInstance);
            boundsMin = expansion.boundsMin;
            boundsMax = expansion.boundsMax;

            if (rigHandle != null
                    && (boundsMax.x <= boundsMin.x || boundsMax.y <= boundsMin.y || boundsMax.z <= boundsMin.z))
                throwException("Rigged mesh \"" + resourceName + "\" has zero extent on at least one axis — "
                        + "cannot derive an entity-scale ratio from a mesh with no size. File: " + file.getName());
        } else if (hasSubVoxels) {

            QuadExpansionStruct expansion = expandSubVoxels(arpg, vaoInstance, file);
            subVoxelVertices = expansion.vertices;
            vboHandle = vboManager.addVBOFromData(resourceName, expansion.vertices, vaoInstance);
            iboHandle = iboManager.addIBOFromData(resourceName, expansion.indices, vaoInstance);
            boundsMin = expansion.boundsMin;
            boundsMax = expansion.boundsMax;
        } else {
            vboHandle = vboManager.getVBOHandleDirect(resourceName);
            iboHandle = iboManager.getIBOHandleDirect(resourceName);
            boundsMin = new Vector3();
            boundsMax = new Vector3();
        }

        if (vboHandle == null || iboHandle == null)
            return null;

        MeshHandle meshHandle = create(MeshHandle.class);
        meshHandle.constructor(resourceName, vaoInstance, vboHandle, iboHandle, rigHandle, boundsMin, boundsMax);

        if (riggedExpansion != null)
            meshManager.applyRiggedMesh(meshHandle, riggedExpansion.riggedMesh, riggedExpansion.morphEntries);

        if (subVoxelVertices != null)
            SubVoxelMeshUtility.collectTiles(subVoxelVertices, subVoxelVertices.length, meshHandle.getTiles());

        return meshHandle;
    }

    // Rig Resolution \\

    private RigHandle resolveRig(ArpgObjectStruct arpg) {

        if (!meshManager.isRiggedMesh(arpg))
            return null;

        return rigManager.getRigHandleFromRigName(arpg.get("rig").getAsString());
    }

    // Quad Detection \\

    private boolean hasQuadEntries(ArpgObjectStruct arpg) {

        if (!hasValidElement(arpg, "vbo"))
            return false;

        ArpgElementStruct vboEl = arpg.get("vbo");

        if (!vboEl.isArray())
            return false;

        for (ArpgElementStruct el : vboEl.getAsArray())
            if (el.isObject())
                return true;

        return false;
    }

    // Quad Expansion \\

    private QuadExpansionStruct expandVBO(
            ArpgObjectStruct arpg,
            VAOInstance vaoInstance,
            File file) {

        int vertStride = vaoInstance.getVAOData().getVertStride();
        FloatArrayList vertices = new FloatArrayList();
        ShortArrayList quadIndices = new ShortArrayList();
        int currentVertex = 0;

        for (ArpgElementStruct element : arpg.getAsArray("vbo")) {

            if (element.isArray()) {

                ArpgArrayStruct vertex = element.getAsArray();

                if (vertex.size() != vertStride)
                    throwException("Vertex attribute count mismatch. Expected "
                            + vertStride + " floats but got " + vertex.size()
                            + " in file: " + file.getName());

                for (ArpgElementStruct val : vertex)
                    vertices.add(val.getAsFloat());

                currentVertex++;
            } else if (element.isObject()) {
                expandQuad(
                        element.getAsObject(),
                        vertices,
                        quadIndices,
                        currentVertex,
                        vertStride,
                        file);
                currentVertex += 4;
            } else
                throwException("VBO element must be a vertex array or quad object in file: "
                        + file.getName());
        }

        ShortArrayList allIndices = new ShortArrayList();

        if (hasValidElement(arpg, "ibo"))
            for (ArpgElementStruct idx : arpg.getAsArray("ibo")) {

                int value = idx.getAsInt();

                if (value < 0 || value > 0xFFFF)
                    throwException("Index out of 16-bit range: " + value
                            + " in file: " + file.getName());

                allIndices.add((short) value);
            }

        allIndices.addAll(quadIndices);

        if (allIndices.isEmpty())
            throwException("No index data produced for file: " + file.getName()
                    + ". Provide an explicit 'ibo' for raw verts and/or include quad entries.");

        Vector3 boundsMin = new Vector3();
        Vector3 boundsMax = new Vector3();
        meshManager.computeBounds(vertices, vertStride, boundsMin, boundsMax);

        return new QuadExpansionStruct(vertices.toFloatArray(), allIndices.toShortArray(), boundsMin, boundsMax);
    }

    // Rigged Expansion \\

    // A rigged mesh parsed into its shared form and built from it, exactly as the character editor rebuilds it
    private QuadExpansionStruct expandRigged(ArpgObjectStruct arpg, VAOInstance vaoInstance, File file) {

        validateRiggedLayout(vaoInstance, file);

        RiggedMeshStruct mesh = meshManager.parseRiggedMesh(arpg, file.getName());

        if (!meshManager.fitsRiggedMeshLimit(mesh))
            throwException("Rigged mesh has " + mesh.getFaceCount() + " quads — every corner is its own vertex and "
                    + "at most " + EngineSetting.RIGGED_MESH_VERT_LIMIT + " fit one mesh. File: " + file.getName());

        FloatArrayList vertices = new FloatArrayList();
        ShortArrayList indices = new ShortArrayList();
        FloatArrayList morphEntries = new FloatArrayList();

        meshManager.buildRiggedGeometry(mesh, vertices, indices, morphEntries);

        if (indices.isEmpty())
            throwException("No index data produced for file: " + file.getName()
                    + ". A rigged mesh needs at least one quad entry.");

        Vector3 boundsMin = new Vector3();
        Vector3 boundsMax = new Vector3();
        meshManager.computeBounds(vertices, EngineSetting.RIGGED_MESH_VERTEX_STRIDE, boundsMin, boundsMax);

        QuadExpansionStruct expansion = new QuadExpansionStruct(
                vertices.toFloatArray(), indices.toShortArray(), boundsMin, boundsMax);
        expansion.riggedMesh = mesh;
        expansion.morphEntries = morphEntries;

        return expansion;
    }

    private void validateRiggedLayout(VAOInstance vaoInstance, File file) {

        int[] attrSizes = vaoInstance.getVAOData().getAttrSizes();

        if (vaoInstance.getVAOData().getVertStride() != EngineSetting.RIGGED_MESH_VERTEX_STRIDE
                || attrSizes[0] != EngineSetting.RIGGED_MESH_POSITION_FLOATS
                || attrSizes[1] != EngineSetting.RIGGED_MESH_UV_FLOATS)
            throwException("Rigged mesh must declare the \"vao\" [" + EngineSetting.RIGGED_MESH_POSITION_FLOATS
                    + ", " + EngineSetting.RIGGED_MESH_UV_FLOATS + "] — a position and a UV for every corner. File: "
                    + file.getName());
    }

    // Sub-Voxel Expansion \\

    private QuadExpansionStruct expandSubVoxels(ArpgObjectStruct arpg, VAOInstance vaoInstance, File file) {

        int vertStride = vaoInstance.getVAOData().getVertStride();

        if (vertStride != EngineSetting.SUB_VOXEL_VERTEX_STRIDE)
            throwException("Sub-voxel mesh requires a VAO with a vertex stride of "
                    + EngineSetting.SUB_VOXEL_VERTEX_STRIDE + ", found " + vertStride
                    + " in file: " + file.getName());

        FloatArrayList vertices = new FloatArrayList();
        ShortArrayList indices = new ShortArrayList();
        subVoxelManager.buildGeometry(subVoxelManager.parseModel(arpg), vertices, indices);

        if (indices.isEmpty())
            throwException("Sub-voxel mesh has no filled cells in file: " + file.getName());

        Vector3 boundsMin = new Vector3();
        Vector3 boundsMax = new Vector3();
        meshManager.computeBounds(vertices, vertStride, boundsMin, boundsMax);

        return new QuadExpansionStruct(vertices.toFloatArray(), indices.toShortArray(), boundsMin, boundsMax);
    }

    private void expandQuad(
            ArpgObjectStruct quadObj,
            FloatArrayList vertices,
            ShortArrayList quadIndices,
            int baseVertex,
            int vertStride,
            File file) {

        if (!quadObj.has("quad") || quadObj.get("quad").isNull())
            throwException("Quad object missing 'quad' array in file: " + file.getName());

        ArpgArrayStruct positions = quadObj.getAsArray("quad");

        if (positions.size() != 4)
            throwException("Quad 'quad' array must have exactly 4 corners in file: " + file.getName());

        if (quadObj.has("texture") && !quadObj.get("texture").isNull())
            throwException("Quad names a texture in file: " + file.getName() + ". Only rigged meshes draw textured "
                    + "quads, each corner taking its UV across the tile; a plain quad carries its vertex data whole.");

        for (int i = 0; i < 4; i++) {

            ArpgArrayStruct corner = positions.get(i).getAsArray();

            if (corner.size() != vertStride)
                throwException("Quad corner " + i + " has " + corner.size()
                        + " floats, expected " + vertStride + " in file: " + file.getName());

            for (ArpgElementStruct val : corner)
                vertices.add(val.getAsFloat());
        }

        quadIndices.add((short) baseVertex);
        quadIndices.add((short) (baseVertex + 1));
        quadIndices.add((short) (baseVertex + 2));
        quadIndices.add((short) (baseVertex + 2));
        quadIndices.add((short) (baseVertex + 3));
        quadIndices.add((short) baseVertex);
    }

    // Utility \\

    private boolean hasValidElement(ArpgObjectStruct arpg, String key) {
        return arpg.has(key) && !arpg.get(key).isNull();
    }
}