package application.bootstrap.itempipeline.tooltype;

public enum ToolSwing {

    /*
     * How a tool type is swung, named in lower case by tool data. An overhead
     * swing comes down on what it strikes, the way a pick or a shovel bites
     * into the ground; a level swing sweeps across from the side, the way an
     * axe bites into a trunk, and plays its own action so the animation tree
     * can draw it.
     */

    OVERHEAD,
    LEVEL
}
