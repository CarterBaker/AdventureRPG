class MeshBuilder extends BuilderPackage {

    /*
     * Assembles a MeshHandle from registered VAO, VBO and IBO data, expanding
     * quad entries inline. A textured quad's UVs snap to its tile's pixels,
     * and a corner on the tile's border sits a sliver inside it, so nearest
     * sampling along a seam never reads the neighbouring tile of the atlas.
     * Rigged meshes bake per-corner bone weights and a smooth normal, the
     * average of every face meeting at the corner within the smoothing angle,
     * so a low-poly body shades as one continuous surface; they record their
     * raw bounds. Meshes declaring subvoxels are generated by SubVoxelManager
     * instead. Bootstrap only.
     */

    // Internal
    private MeshManager meshManager;
    private VBOManager vboManager;
    private IBOManager iboManager;
    private TextureManager textureManager;
    private RigManager rigManager;
    private SubVoxelManager subVoxelManager;

    // Base \\

    @Override
    protected void get() {
        this.meshManager = get(MeshManager.class);
        this.vboManager = get(VBOManager.class);
        this.iboManager = get(IBOManager.class);
        this.textureManager = get(TextureManager.class);
        this.rigManager = get(RigManager.class);
        this.subVoxelManager = get(SubVoxelManager.class);
    }

    // Build \\

    MeshHandle buildMeshHandle(
            File root,
            File file,
            VAOInstance vaoInstance) {

        ArpgObjectStruct arpg = ArpgUtility.loadObject(file);
        String resourceName = FileUtility.getPathWithFileNameWithoutExtension(root, file);
        RigHandle rigHandle = resolveRig(arpg);
        boolean hasQuads = hasQuadEntries(arpg);
        boolean hasSubVoxels = subVoxelManager.hasSubVoxels(arpg);

        if (hasSubVoxels && (rigHandle != null || hasQuads))
            throwException("Sub-voxel mesh \"" + resourceName + "\" cannot also declare a rig or quad entries — "
                    + "its geometry is generated entirely from its cubes. File: " + file.getName());

        if (rigHandle != null && !hasQuads)
            throwException("Rigged mesh \"" + resourceName + "\" must declare its vertex data through quad "
                    + "entries — bone weighting and entity-scale bounds can only be resolved from quad-expanded "
                    + "vertex data. File: " + file.getName());

        VBOHandle vboHandle;
        IBOHandle iboHandle;
        Vector3 boundsMin;
        Vector3 boundsMax;

        if (hasQuads) {

            QuadExpansionStruct expansion = expandVBO(arpg, vaoInstance, rigHandle, file);
            vboHandle = vboManager.addVBOFromData(resourceName, expansion.vertices, vaoInstance);
            iboHandle = iboManager.addIBOFromData(resourceName, expansion.indices, vaoInstance);
            boundsMin = expansion.boundsMin;
            boundsMax = expansion.boundsMax;

            if (rigHandle != null
                    && (boundsMax.x <= boundsMin.x || boundsMax.y <= boundsMin.y || boundsMax.z <= boundsMin.z))
                throwException("Rigged mesh \"" + resourceName + "\" has zero extent on at least one axis — "
                        + "cannot derive an entity-scale ratio from a mesh with no size. File: " + file.getName());
        } else if (hasSubVoxels) {

            QuadExpansionStruct expansion = expandSubVoxels(arpg, vaoInstance, file);
            vboHandle = vboManager.addVBOFromData(resourceName, expansion.vertices, vaoInstance);
            iboHandle = iboManager.addIBOFromData(resourceName, expansion.indices, vaoInstance);
            boundsMin = expansion.boundsMin;
            boundsMax = expansion.boundsMax;
        } else {
            vboHandle = vboManager.getVBOHandleDirect(resourceName);
            iboHandle = iboManager.getIBOHandleDirect(resourceName);
            boundsMin = new Vector3();
            boundsMax = new Vector3();
        }

        if (vboHandle == null || iboHandle == null)
            return null;

        MeshHandle meshHandle = create(MeshHandle.class);
        meshHandle.constructor(vaoInstance, vboHandle, iboHandle, rigHandle, boundsMin, boundsMax);

        return meshHandle;
    }

    // Rig Resolution \\

    private RigHandle resolveRig(ArpgObjectStruct arpg) {

        if (!hasValidElement(arpg, "rig"))
            return null;

        return rigManager.getRigHandleFromRigName(arpg.get("rig").getAsString());
    }

    // Quad Detection \\

    private boolean hasQuadEntries(ArpgObjectStruct arpg) {

        if (!hasValidElement(arpg, "vbo"))
            return false;

        ArpgElementStruct vboEl = arpg.get("vbo");

        if (!vboEl.isArray())
            return false;

        for (ArpgElementStruct el : vboEl.getAsArray())
            if (el.isObject())
                return true;

        return false;
    }

    // Quad Expansion \\

    private QuadExpansionStruct expandVBO(
            ArpgObjectStruct arpg,
            VAOInstance vaoInstance,
            RigHandle rigHandle,
            File file) {

        int vertStride = vaoInstance.getVAOData().getVertStride();
        FloatArrayList vertices = new FloatArrayList();
        ShortArrayList quadIndices = new ShortArrayList();
        int currentVertex = 0;

        for (ArpgElementStruct element : arpg.getAsArray("vbo")) {

            if (element.isArray()) {

                ArpgArrayStruct vertex = element.getAsArray();

                if (vertex.size() != vertStride)
                    throwException("Vertex attribute count mismatch. Expected "
                            + vertStride + " floats but got " + vertex.size()
                            + " in file: " + file.getName());

                for (ArpgElementStruct val : vertex)
                    vertices.add(val.getAsFloat());

                currentVertex++;
            } else if (element.isObject()) {
                expandQuad(
                        element.getAsObject(),
                        vertices,
                        quadIndices,
                        currentVertex,
                        vertStride,
                        vaoInstance,
                        rigHandle,
                        file);
                currentVertex += 4;
            } else
                throwException("VBO element must be a vertex array or quad object in file: "
                        + file.getName());
        }

        ShortArrayList allIndices = new ShortArrayList();

        if (hasValidElement(arpg, "ibo"))
            for (ArpgElementStruct idx : arpg.getAsArray("ibo")) {

                int value = idx.getAsInt();

                if (value < 0 || value > 0xFFFF)
                    throwException("Index out of 16-bit range: " + value
                            + " in file: " + file.getName());

                allIndices.add((short) value);
            }

        allIndices.addAll(quadIndices);

        if (allIndices.isEmpty())
            throwException("No index data produced for file: " + file.getName()
                    + ". Provide an explicit 'ibo' for raw verts and/or include quad entries.");

        if (rigHandle != null)
            smoothRigNormals(vertices, vertStride);

        Vector3 boundsMin = new Vector3();
        Vector3 boundsMax = new Vector3();
        meshManager.computeBounds(vertices, vertStride, boundsMin, boundsMax);

        return new QuadExpansionStruct(vertices.toFloatArray(), allIndices.toShortArray(), boundsMin, boundsMax);
    }

    // Sub-Voxel Expansion \\

    private QuadExpansionStruct expandSubVoxels(ArpgObjectStruct arpg, VAOInstance vaoInstance, File file) {

        int vertStride = vaoInstance.getVAOData().getVertStride();

        if (vertStride != EngineSetting.SUB_VOXEL_VERTEX_STRIDE)
            throwException("Sub-voxel mesh requires a VAO with a vertex stride of "
                    + EngineSetting.SUB_VOXEL_VERTEX_STRIDE + ", found " + vertStride
                    + " in file: " + file.getName());

        FloatArrayList vertices = new FloatArrayList();
        ShortArrayList indices = new ShortArrayList();
        subVoxelManager.buildGeometry(subVoxelManager.parseModel(arpg), vertices, indices);

        if (indices.isEmpty())
            throwException("Sub-voxel mesh has no filled cells in file: " + file.getName());

        Vector3 boundsMin = new Vector3();
        Vector3 boundsMax = new Vector3();
        meshManager.computeBounds(vertices, vertStride, boundsMin, boundsMax);

        return new QuadExpansionStruct(vertices.toFloatArray(), indices.toShortArray(), boundsMin, boundsMax);
    }

    private static final float[][] DEFAULT_CORNER_LOCAL_UVS = {
            { 0, 0 }, { 1, 0 }, { 1, 1 }, { 0, 1 }
    };

    private void expandQuad(
            ArpgObjectStruct quadObj,
            FloatArrayList vertices,
            ShortArrayList quadIndices,
            int baseVertex,
            int vertStride,
            VAOInstance vaoInstance,
            RigHandle rigHandle,
            File file) {

        if (!quadObj.has("quad") || quadObj.get("quad").isNull())
            throwException("Quad object missing 'quad' array in file: " + file.getName());

        ArpgArrayStruct positions = quadObj.getAsArray("quad");

        if (positions.size() != 4)
            throwException("Quad 'quad' array must have exactly 4 corners in file: " + file.getName());

        boolean hasTexture = quadObj.has("texture") && !quadObj.get("texture").isNull();
        int boneFloatCount = rigHandle != null ? EngineSetting.MAX_BONE_INFLUENCES * 2 : 0;
        int normalFloatCount = rigHandle != null ? EngineSetting.SKINNED_NORMAL_FLOATS : 0;
        float[][] boneData = rigHandle != null
                ? resolveCornerBoneWeights(quadObj, rigHandle, file)
                : null;
        float[] faceNormal = rigHandle != null
                ? resolveFaceNormal(positions)
                : null;

        if (hasTexture) {

            validateVAOUVCompatibility(vaoInstance, rigHandle != null, file);

            int posStride = vertStride - 2 - boneFloatCount - normalFloatCount;
            TextureHandle textureHandle = textureManager.getTextureHandleFromTextureName(
                    quadObj.get("texture").getAsString());
            int tileWidth = textureHandle.getTileWidth();
            int tileHeight = textureHandle.getTileHeight();
            float u0 = textureHandle.getU0();
            float u1 = textureHandle.getU1();
            float v0 = textureHandle.getV0();
            float v1 = textureHandle.getV1();
            float[][] localUVs = resolveLocalUVs(quadObj, file);

            for (int i = 0; i < 4; i++) {

                ArpgArrayStruct pos = positions.get(i).getAsArray();

                if (pos.size() != posStride)
                    throwException("Textured quad corner " + i + " has " + pos.size()
                            + " floats, expected " + posStride + " in file: " + file.getName());

                for (ArpgElementStruct val : pos)
                    vertices.add(val.getAsFloat());

                vertices.add(snapUV(localUVs[i][0], u0, u1, tileWidth));
                vertices.add(snapUV(localUVs[i][1], v0, v1, tileHeight));

                if (boneData != null)
                    for (int b = 0; b < boneFloatCount; b++)
                        vertices.add(boneData[i][b]);

                if (faceNormal != null)
                    for (int n = 0; n < normalFloatCount; n++)
                        vertices.add(faceNormal[n]);
            }
        } else {

            int posStride = vertStride - boneFloatCount - normalFloatCount;

            for (int i = 0; i < 4; i++) {

                ArpgArrayStruct corner = positions.get(i).getAsArray();

                if (corner.size() != posStride)
                    throwException("Untextured quad corner " + i + " has " + corner.size()
                            + " floats, expected " + posStride + " in file: " + file.getName());

                for (ArpgElementStruct val : corner)
                    vertices.add(val.getAsFloat());

                if (boneData != null)
                    for (int b = 0; b < boneFloatCount; b++)
                        vertices.add(boneData[i][b]);

                if (faceNormal != null)
                    for (int n = 0; n < normalFloatCount; n++)
                        vertices.add(faceNormal[n]);
            }
        }

        quadIndices.add((short) baseVertex);
        quadIndices.add((short) (baseVertex + 1));
        quadIndices.add((short) (baseVertex + 2));
        quadIndices.add((short) (baseVertex + 2));
        quadIndices.add((short) (baseVertex + 3));
        quadIndices.add((short) baseVertex);
    }

    // Normals \\

    // The quad's diagonals crossed: its normal, as long as twice its area, so a larger face weighs more when smoothed
    private float[] resolveFaceNormal(ArpgArrayStruct positions) {

        ArpgArrayStruct c0 = positions.get(0).getAsArray();
        ArpgArrayStruct c1 = positions.get(1).getAsArray();
        ArpgArrayStruct c2 = positions.get(2).getAsArray();
        ArpgArrayStruct c3 = positions.get(3).getAsArray();

        float ax = c2.get(0).getAsFloat() - c0.get(0).getAsFloat();
        float ay = c2.get(1).getAsFloat() - c0.get(1).getAsFloat();
        float az = c2.get(2).getAsFloat() - c0.get(2).getAsFloat();
        float bx = c3.get(0).getAsFloat() - c1.get(0).getAsFloat();
        float by = c3.get(1).getAsFloat() - c1.get(1).getAsFloat();
        float bz = c3.get(2).getAsFloat() - c1.get(2).getAsFloat();

        return new float[] { ay * bz - az * by, az * bx - ax * bz, ax * by - ay * bx };
    }

    // Each corner's normal becomes the sum of the face normals meeting at its exact position within the smoothing
    // angle. Authored winding is free to vary, so each face is turned to the corner's own side before it is added
    // and only the line of the result is kept; the shader turns it toward the face it shades.
    private void smoothRigNormals(FloatArrayList vertices, int vertStride) {

        int vertexCount = vertices.size() / vertStride;
        int normalOffset = vertStride - EngineSetting.SKINNED_NORMAL_FLOATS;
        float[] faceNormals = new float[vertexCount * EngineSetting.SKINNED_NORMAL_FLOATS];
        Object2ObjectOpenHashMap<Vector3, IntArrayList> position2Vertices = new Object2ObjectOpenHashMap<>();

        for (int i = 0; i < vertexCount; i++) {

            int base = i * vertStride;

            for (int n = 0; n < EngineSetting.SKINNED_NORMAL_FLOATS; n++)
                faceNormals[i * EngineSetting.SKINNED_NORMAL_FLOATS + n] = vertices.getFloat(base + normalOffset + n);

            position2Vertices.computeIfAbsent(resolvePositionKey(vertices, base), key -> new IntArrayList()).add(i);
        }

        for (int i = 0; i < vertexCount; i++) {

            int base = i * vertStride;
            IntArrayList shared = position2Vertices.get(resolvePositionKey(vertices, base));
            float sumX = 0f;
            float sumY = 0f;
            float sumZ = 0f;

            for (int s = 0; s < shared.size(); s++) {

                int other = shared.getInt(s) * EngineSetting.SKINNED_NORMAL_FLOATS;
                float alignment = resolveAlignment(faceNormals, i * EngineSetting.SKINNED_NORMAL_FLOATS, other);

                if (Math.abs(alignment) < EngineSetting.SKINNED_NORMAL_SMOOTH_COSINE)
                    continue;

                float side = Math.signum(alignment);

                sumX += faceNormals[other] * side;
                sumY += faceNormals[other + 1] * side;
                sumZ += faceNormals[other + 2] * side;
            }

            float length = (float) Math.sqrt(sumX * sumX + sumY * sumY + sumZ * sumZ);

            if (length <= 0f)
                continue;

            vertices.set(base + normalOffset, sumX / length);
            vertices.set(base + normalOffset + 1, sumY / length);
            vertices.set(base + normalOffset + 2, sumZ / length);
        }
    }

    // The cosine between two face normals, signed by whether they point the same way; 0 when either has no area
    private static float resolveAlignment(float[] faceNormals, int a, int b) {

        float ax = faceNormals[a];
        float ay = faceNormals[a + 1];
        float az = faceNormals[a + 2];
        float bx = faceNormals[b];
        float by = faceNormals[b + 1];
        float bz = faceNormals[b + 2];
        float lengths = (float) Math.sqrt((ax * ax + ay * ay + az * az) * (bx * bx + by * by + bz * bz));

        if (lengths <= 0f)
            return 0f;

        return (ax * bx + ay * by + az * bz) / lengths;
    }

    // A vertex's position as a map key; adding zero folds negative zero into zero, so equal positions hash alike
    private static Vector3 resolvePositionKey(FloatArrayList vertices, int base) {
        return new Vector3(
                vertices.getFloat(base) + 0f,
                vertices.getFloat(base + 1) + 0f,
                vertices.getFloat(base + 2) + 0f);
    }

    // Bone Weights \\

    private float[][] resolveCornerBoneWeights(ArpgObjectStruct quadObj, RigHandle rigHandle, File file) {

        if (!hasValidElement(quadObj, "bones"))
            throwException("Quad is missing \"bones\" in a rig-declaring mesh. Every quad must "
                    + "specify at least one bone. File: " + file.getName());

        ArpgArrayStruct bonesArray = quadObj.getAsArray("bones");
        float[][] cornerBoneData = new float[EngineSetting.QUAD_VERTEX_COUNT][];
        boolean perCorner = bonesArray.size() > 0 && bonesArray.get(0).isArray();

        if (perCorner && bonesArray.size() != EngineSetting.QUAD_VERTEX_COUNT)
            throwException("Per-corner quad \"bones\" must declare exactly " + EngineSetting.QUAD_VERTEX_COUNT
                    + " influence lists, found " + bonesArray.size() + " in file: " + file.getName());

        for (int corner = 0; corner < EngineSetting.QUAD_VERTEX_COUNT; corner++)
            cornerBoneData[corner] = perCorner
                    ? resolveBoneWeights(bonesArray.get(corner).getAsArray(), rigHandle, file)
                    : resolveBoneWeights(bonesArray, rigHandle, file);

        return cornerBoneData;
    }

    private float[] resolveBoneWeights(ArpgArrayStruct bonesArray, RigHandle rigHandle, File file) {

        int influenceCount = bonesArray.size();

        if (influenceCount == 0 || influenceCount > EngineSetting.MAX_BONE_INFLUENCES)
            throwException("Quad \"bones\" must declare between 1 and "
                    + EngineSetting.MAX_BONE_INFLUENCES + " entries, found " + influenceCount
                    + " in file: " + file.getName());

        float[] result = new float[EngineSetting.MAX_BONE_INFLUENCES * 2];
        float weightSum = 0f;

        for (int i = 0; i < influenceCount; i++) {

            ArpgObjectStruct entry = bonesArray.get(i).getAsObject();
            String boneName = ArpgUtility.validateString(entry, "bone");
            float weight = entry.has("weight") ? entry.get("weight").getAsFloat() : 1f;

            if (!rigHandle.hasBone(boneName))
                throwException("Quad references unknown bone \"" + boneName
                        + "\" for rig in file: " + file.getName());

            if (weight < 0f)
                throwException("Bone weight cannot be negative for bone \"" + boneName
                        + "\" in file: " + file.getName());

            result[i] = rigHandle.getBoneIndex(boneName);
            result[EngineSetting.MAX_BONE_INFLUENCES + i] = weight;
            weightSum += weight;
        }

        if (Math.abs(weightSum - 1f) > EngineSetting.BONE_WEIGHT_SUM_EPSILON)
            throwException("Quad bone weights must sum to 1.0, got " + weightSum
                    + " in file: " + file.getName());

        return result;
    }

    // VAO Compatibility \\

    private void validateVAOUVCompatibility(VAOInstance vaoInstance, boolean hasBones, File file) {

        int[] attrSizes = vaoInstance.getVAOData().getAttrSizes();

        if (attrSizes == null || attrSizes.length == 0)
            throwException("VAO has no attribute layout — cannot inject UVs in file: " + file.getName());

        int uvAttrIndex = hasBones ? attrSizes.length - 4 : attrSizes.length - 1;

        if (uvAttrIndex < 0 || attrSizes[uvAttrIndex] != 2)
            throwException("Textured quad requires the last declared VAO attribute size 2, found "
                    + (uvAttrIndex < 0 ? "none" : attrSizes[uvAttrIndex]) + " in file: " + file.getName()
                    + ". Remove 'texture' from the quad or fix the VAO layout.");
    }

    // UV Snapping \\

    private float[][] resolveLocalUVs(ArpgObjectStruct quadObj, File file) {

        if (!quadObj.has("uvs") || quadObj.get("uvs").isNull())
            return DEFAULT_CORNER_LOCAL_UVS;

        ArpgArrayStruct uvsArray = quadObj.getAsArray("uvs");

        if (uvsArray.size() != 4)
            throwException("Quad 'uvs' must have exactly 4 entries in file: " + file.getName());

        float[][] localUVs = new float[4][2];

        for (int i = 0; i < 4; i++) {
            ArpgArrayStruct pair = uvsArray.get(i).getAsArray();
            if (pair.size() != 2)
                throwException("Quad 'uvs' entry " + i + " must have 2 values in file: " + file.getName());
            localUVs[i][0] = pair.get(0).getAsFloat();
            localUVs[i][1] = pair.get(1).getAsFloat();
        }

        return localUVs;
    }

    private float snapUV(float local, float tileMin, float tileMax, int tilePixelSize) {

        int pixel = Math.round(local * tilePixelSize);
        float inset = EngineSetting.MESH_UV_EDGE_INSET_TEXELS / tilePixelSize;
        float snapped = Math.clamp(pixel / (float) tilePixelSize, inset, 1f - inset);

        return tileMin + snapped * (tileMax - tileMin);
    }

    // Utility \\

    private boolean hasValidElement(ArpgObjectStruct arpg, String key) {
        return arpg.has(key) && !arpg.get(key).isNull();
    }
}