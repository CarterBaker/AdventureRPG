package application.bootstrap.combatpipeline.combat;

public enum BlowOutcome {

    /*
     * What a blow did to the world thing it landed on. TURNED means it was
     * turned aside and did nothing, as a block shrugs off a tool it does not
     * yield to; WORKED means it told without breaking through, as a notch
     * cut in a trunk or a stroke counted against a block; BROKEN means what
     * it struck gave way, and a thrown blow flies on through the gap.
     */

    TURNED,
    WORKED,
    BROKEN
}
